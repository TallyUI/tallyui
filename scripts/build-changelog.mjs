#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export const PACKAGE_DIRS = [
  'packages/core', 'packages/database', 'packages/primitives', 'packages/components',
  'packages/storage-sqlite', 'packages/pos', 'packages/theme',
  'connectors/woocommerce', 'connectors/medusa', 'connectors/shopify', 'connectors/vendure',
];

export function parseChangelog(text) {
  const sections = [];
  for (const line of text.split(/\r?\n/)) {
    const heading = line.match(/^## (.+)$/);
    if (heading) sections.push({ version: heading[1], lines: [] });
    else if (sections.length) sections.at(-1).lines.push(line);
  }
  return sections.map(({ version, lines }) => ({ version, body: lines.join('\n') }));
}

export function isRelease(version) {
  return /^\d+\.\d+\.\d+$/.test(version);
}

export function cleanBody(body) {
  let dependencyIndent;
  const lines = body.split(/\r?\n/).filter(line => {
    const updated = line.match(/^([ \t]*)- Updated dependencies\b/);
    if (updated) {
      dependencyIndent = updated[1].length;
      return false;
    }
    const dependency = line.match(/^([ \t]*)- @tallyui\//);
    if (dependency && dependency[1].length > dependencyIndent) return false;
    if (line.trim()) dependencyIndent = undefined;
    return true;
  });
  const kept = lines.filter((line, index) => {
    if (!/^### .+ Changes[ \t]*$/.test(line)) return true;
    for (let i = index + 1; i < lines.length && !/^### /.test(lines[i]); i++) {
      if (/^[ \t]*- /.test(lines[i])) return true;
    }
    return false;
  });
  while (kept.length && !kept[0].trim()) kept.shift();
  while (kept.length && !kept.at(-1).trim()) kept.pop();
  return kept.join('\n');
}

export function escapeMdx(markdown) {
  let fenceLength = 0;
  return markdown.split('\n').map(line => {
    const fence = line.match(/^[ \t]*(`{3,})([^`]*)$/);
    if (fence) {
      if (!fenceLength) fenceLength = fence[1].length;
      else if (fence[1].length >= fenceLength && !fence[2].trim()) fenceLength = 0;
      return line;
    }
    if (fenceLength) return line;
    const parts = line.split(/(`+)/);
    const escaped = [];
    for (let i = 0; i < parts.length; i++) {
      const end = i % 2 === 1 ? parts.indexOf(parts[i], i + 1) : -1;
      if (end !== -1) {
        escaped.push(parts.slice(i, end + 1).join(''));
        i = end;
      } else escaped.push(parts[i].replace(/[{}<]/g, '\\$&'));
    }
    return escaped.join('');
  }).join('\n');
}

export function compareVersions(a, b) {
  const left = a.split('.').map(Number);
  const right = b.split('.').map(Number);
  return right[0] - left[0] || right[1] - left[1] || right[2] - left[2];
}

export function buildChangelogMdx(entries) {
  const names = PACKAGE_DIRS.map(dir => dir.replace('packages/', '@tallyui/').replace('connectors/', '@tallyui/connector-'));
  const packages = entries.map(({ name, text }) => ({ name, sections: parseChangelog(text) }))
    .sort((a, b) => names.indexOf(a.name) - names.indexOf(b.name));
  const versions = [...new Set(packages.flatMap(pkg => pkg.sections.map(section => section.version).filter(isRelease)))]
    .sort(compareVersions);
  const blocks = [
    '---\ntitle: Changelog\ndescription: Released changes to the @tallyui packages, newest first.\n---',
    "{/* Generated by scripts/build-changelog.mjs from each package's CHANGELOG.md. Do not edit: run pnpm changelog:docs after a release. */}",
  ];
  for (const version of versions) {
    blocks.push(`## ${version}`);
    for (const pkg of packages) {
      const section = pkg.sections.find(section => section.version === version);
      if (!section) continue;
      const body = cleanBody(section.body);
      if (body) blocks.push(`### ${pkg.name}`, escapeMdx(body.replace(/^### (.+ Changes)[ \t]*$/gm, '#### $1')));
    }
  }
  return blocks.join('\n\n') + '\n';
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const entries = PACKAGE_DIRS.map(dir => ({
    name: JSON.parse(readFileSync(`${dir}/package.json`, 'utf8')).name,
    text: readFileSync(`${dir}/CHANGELOG.md`, 'utf8'),
  }));
  const page = buildChangelogMdx(entries);
  const output = 'apps/web/content/docs/changelog.mdx';
  if (process.argv.includes('--check')) {
    if (!existsSync(output) || readFileSync(output, 'utf8') !== page) {
      console.error('Changelog page is missing or stale; run pnpm changelog:docs.');
      process.exit(1);
    }
  } else {
    writeFileSync(output, page);
    console.log(page.match(/^## (.+)$/m)[1]);
  }
}
